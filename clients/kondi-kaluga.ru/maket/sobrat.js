const ZAPAS = `,"system-ui","Segoe UI","Helvetica Neue","Arial","sans-serif"`;
const konfig = konfigJs
  .replace(/^\s*tailwind\.config\s*=\s*/, 'module.exports = ')
  .replace(/\["Manrope"\]/g, `["Manrope"${ZAPAS}]`)
  .replace(/^module\.exports = \{/, 'module.exports = {content:["./site/index.html"],');

fs.writeFileSync(path.join(__dirname, 'tailwind.config.cjs'), konfig + '\n');
fs.writeFileSync(path.join(__dirname, 'vhod.css'), '@tailwind base;\n@tailwind components;\n@tailwind utilities;\n');

