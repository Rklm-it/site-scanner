// Градиентный текст заголовка. В 2019 это было приёмом, сейчас — подпись
// нейросети; мы этот приём сами запрещали в промптах, а он приехал.
$('[class*="bg-clip-text"]').each((_, el) => {
  $(el).attr('class', ($(el).attr('class') || '')
    .replace(/\b(text-transparent|bg-clip-text|bg-gradient-to-\w+|from-\S+|via-\S+|to-\S+)\b/g, '')
    .trim() + ' text-primary');
});

// Заголовок первого экрана: 56 px — это подзаголовок. Одно громкое место на
// странице должно быть по-настоящему громким.
$('h1').addClass('lg:!text-[72px] lg:!leading-[76px]');

// Вечное мигание и пульсация точек. Бесконечно двигаться в поле зрения имеет
// право только индикатор загрузки: телефон не спит, глаз цепляется. Шейдера
// первого экрана это не касается — он и есть громкое место, и он выключен на
// телефоне и при prefers-reduced-motion.
['animate-pulse', 'animate-ping', 'animate-bounce', 'animate-spin']
  .forEach((k) => $('.' + k).removeClass(k));

// transition: all — под него рано или поздно попадает раскладка, и кадры
// проседают. Перечисляем то, что реально меняется.
$('[class*="transition-all"]').each((_, el) => {
  $(el).attr('class', ($(el).attr('class') || '').replace(/\btransition-all\b/g, 'transition-colors'));
});

// ── 7. Tailwind собирается, а не считается в браузере ───────────────────────
// В макете стили тянет cdn.tailwindcss.com — это дев-скрипт, он собирает CSS
// прямо в браузере. В бою так не оставляют: лишние 100 КБ и пересчёт на
// каждом заходе. Конфиг Stitch кладёт в <script id="tailwind-config">, отсюда
// его и берём, добавляя запасные шрифты (в Manrope нет знака рубля).

const konfigJs = $('script#tailwind-config').html() || '';
$('script#tailwind-config').remove();

