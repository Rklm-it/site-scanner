// Замены идут одним проходом по регулярке, длинные строки раньше коротких.
// Иначе правило «Вакуум» съедает «Вакуумирование двухступенчатым насосом», а
// результат одной замены попадает под следующую: на этом уже получили
// «Калуга и Калуга и Калужская область».

const KARTA = new Map(ZAMENY);
const ISTOCHNIKI = [...KARTA.keys()].sort((a, b) => b.length - a.length);
const RE = new RegExp(ISTOCHNIKI.map(s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g');

let sdelano = 0;
const nenaydeno = new Set(ISTOCHNIKI);

function projti(uzel) {
  $(uzel).contents().each((_, u) => {
    if (u.type === 'text') {
      const t = u.data.replace(RE, (m) => { nenaydeno.delete(m); sdelano++; return KARTA.get(m); });
      if (t !== u.data) u.data = t;
    } else if (u.type === 'tag' && u.name !== 'script' && u.name !== 'style') {
      projti(u);
    }
  });
}
projti('body');

// ── 2. Удаление узлов целиком ───────────────────────────────────────────────
// Выдуманный номер лицензии, выдуманная почта, выдуманные часы работы.

function udalit(tekst, podnyatsya) {
  let nashli = 0;
  $('body *').each((_, el) => {
    const $e = $(el);
    if ($e.children().length === 0 && $e.text().includes(tekst)) {
      let cel = $e;
      for (let i = 0; i < (podnyatsya || 0); i++) cel = cel.parent();
      cel.remove(); nashli++;
    }
  });
  return nashli;
}

