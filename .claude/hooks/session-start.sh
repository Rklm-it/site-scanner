#!/bin/bash
# Печатает в начало сессии, чем в этом репозитории пользуются вместо ручной
# работы. Вывод SessionStart-хука попадает в контекст, и это единственный
# способ, которым сессия узнаёт про инструменты до первой задачи: CLAUDE.md
# читается не всегда целиком, а список инструментов сам себя не объясняет.
#
# Подключён двумя путями: в .claude/settings.json сканера (для сессий, которые
# настроек машины не видят, — это веб) и в плагине studio (hooks/hooks.json),
# оттуда доезжает до репозиториев клиентов. На машине, где включено и то и
# другое, хук срабатывает дважды — поэтому второй запуск в той же сессии молчит
# по метке: две одинаковые простыни в контексте только мешают читать.
set -u

payload=$(timeout 1 cat 2>/dev/null || true)
session=$(printf '%s' "$payload" | sed -n 's/.*"session_id"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p')

if [ -n "$session" ]; then
  mark="${TMPDIR:-/tmp}/claude-studio-hint-$session"
  [ -e "$mark" ] && exit 0
  : > "$mark" 2>/dev/null || true
fi

echo "Инструменты этой сессии — брать их всегда, когда задача про них, а не"
echo "делать то же самое руками. Разрешения не спрашивать: они для этого и есть."
echo "  • context7 — спросить документацию библиотеки (Vite, React, Tailwind,"
echo "    shadcn, Nuxt, FastAPI) ДО правки кода по ней: память модели отстаёт."
echo "  • playwright — открыть страницу и посмотреть глазами, что получилось:"
echo "    кнопки, узкий экран, консоль. Сдавать вслепую нельзя."
echo "  • скилы: /lovable-site — весь цикл сайта клиента; вид доводить"
echo "    /frontend-design → /web-design-engineer → /web-quality-audit."
echo "    Просят оживить страницу — /web-animation (правила и проверка), и"
echo "    только потом библиотека; первый экран не анимируем: это LCP."
echo "  • вид решается ДО генератора: DESIGN.md у клиента, одно громкое место,"
echo "    фирменный приём, кегли числами. «Спокойный», «минималистичный»,"
echo "    «много воздуха» в промпте запрещены — это заказ на серость."

if ! command -v npx >/dev/null 2>&1; then
  echo "  ! npx на машине нет — MCP-серверы не поднимутся. Запасной путь:"
  echo "    скил /webapp-testing вместо playwright, сайт библиотеки вместо context7."
fi

echo "Инструмента нет в сессии — сказать об этом и пойти запасным путём, не угадывать."
echo "Проверять наличие командой /mcp бесполезно: в приложении Claude она открывает"
echo "каталог коннекторов аккаунта, а не список плагинов. Проверка — попробовать вызвать."
# Серверов два, и это первое, обо что спотыкаются: команда со «своим» путём
# падает как No such file or directory, и выглядит поломкой окружения.
echo "Серверов у владельца ДВА, репозиторий на обоих одинаковый, пути разные:"
echo "  • сканер — /root/site-scanner-main, там docker compose и база лидов;"
echo "  • прототипы — /root/site-scanner, там Caddy и /root/prototypes-static."
echo "Над каждым блоком команд писать, на какой машине он выполняется, и первой"
echo "строкой давать cd с полным путём. Смешивать машины в одном блоке нельзя."
