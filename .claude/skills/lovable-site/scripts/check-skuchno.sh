#!/bin/bash
# Ищет не ошибки, а тишину: страницу, где нигде не громко.
#
# check-shablon.sh ловит то, что модель ДОБАВИЛА лишнего (градиенты, эмодзи,
# стоки). Скучный сайт — обратная беда: в нём ничего не добавлено. Всё серое,
# всё одной ширины, заголовок 36 px, картинки в одинаковых карточках. Grep-ом
# ловится именно отсутствие: считаем крупное, тёмное, широкое — и ругаемся,
# когда счёт нулевой.
#
# Выход 1 — тихо во всех четырёх главных местах разом. Это не вкусовщина, а
# признак, что вид не решали: генератор взял свои дефолты.
set -uo pipefail
export LC_ALL=C.UTF-8

TARGET="${1:-.}"
[ -e "$TARGET" ] || { echo "нет такого пути: $TARGET" >&2; exit 2; }

INC=(--include='*.html' --include='*.js' --include='*.mjs' --include='*.jsx'
     --include='*.ts' --include='*.tsx' --include='*.css' --include='*.vue')

scan() {
  if [ -d "$TARGET" ]; then (cd "$TARGET" && grep -rhoiE "$1" . "${INC[@]}" 2>/dev/null)
  else grep -hoiE "$1" "$TARGET" 2>/dev/null; fi
}
count() { scan "$1" | wc -l | tr -d ' '; }

TIHO=0
say() {  # say <что тихо> <чем чинить>
  TIHO=$((TIHO + 1))
  printf '\n[тихо] %s\n      → %s\n' "$1" "$2"
}

echo "=== Где на этой странице громко? ==="

# 1. Крупный заголовок. text-5xl это 48px — уже мелко для первого экрана.
BIG=$(count 'text-(6|7|8|9)xl|font-size: *([6-9][0-9]|1[0-9]{2})px|clamp\([^)]*(4|5|6|7|8|9)rem')
if [ "$BIG" -eq 0 ]; then
  say "нет ни одного по-настоящему крупного заголовка" \
      "первый экран: 72–120 px на десктопе. 36 px — это подпись под фото, а не заголовок"
else
  printf '\n[есть] крупный заголовок (%s)\n' "$BIG"
fi

# 2. Контраст по фону: тёмная или насыщенная секция.
DARK=$(count 'bg-(black|(neutral|zinc|slate|stone|gray)-(8|9)00)|bg-[a-z]+-(7|8|9)00|background(-color)?: *#[0-3][0-9a-f]{5}')
if [ "$DARK" -eq 0 ]; then
  say "вся страница одного светлого тона" \
      "одна тёмная или насыщенная секция посреди светлой — самый дешёвый способ дать ритм"
else
  printf '[есть] контрастная секция (%s)\n' "$DARK"
fi

# 3. Крупный кадр: во весь экран или во всю ширину, без карточки.
HERO=$(count 'h-screen|min-h-\[?[5-9][0-9]vh|h-\[[5-9][0-9]vh|w-screen|object-cover[^"]*h-\[?[4-9][0-9]{2}')
if [ "$HERO" -eq 0 ]; then
  say "нет ни одного крупного кадра" \
      "хотя бы одна фотография во всю ширину без полей; у ниш с фото это главный рычаг"
else
  printf '[есть] крупный кадр (%s)\n' "$HERO"
fi

# 4. Одна ширина на всю страницу: контейнер есть, полноширинных блоков нет.
BOX=$(count 'max-w-(5|6|7)xl|container mx-auto|max-w-screen-(lg|xl|2xl)')
FULL=$(count 'w-full[^"]*bg-|w-screen|max-w-none|inset-0')
if [ "$BOX" -ge 4 ] && [ "$FULL" -eq 0 ]; then
  say "всё уложено в одну колонку одной ширины ($BOX контейнеров)" \
      "часть блоков во всю ширину: фото, тёмная полоса, таблица. Иначе страница читается как документ"
fi

echo
echo "=== Однообразие ==="

# Сетка карточек как единственный приём.
G3=$(count 'grid-cols-3|md:grid-cols-3|lg:grid-cols-3')
if [ "$G3" -ge 3 ]; then
  printf '[однообразно] сетка 3 в ряд повторяется %s раз\n' "$G3"
  printf '      → один блок сделать иначе: список, крупная пара, полоса во всю ширину\n'
fi

# Мелкий текст как основной.
SMALL=$(count 'text-sm|text-xs'); LARGE=$(count 'text-lg|text-xl|text-2xl')
if [ "$SMALL" -ge 10 ] && [ "$SMALL" -gt "$LARGE" ]; then
  printf '[однообразно] мелкий текст преобладает (%s мелких против %s крупных)\n' "$SMALL" "$LARGE"
  printf '      → основной текст 18–20 px; 14 px читают с телефона щурясь\n'
fi

# Ни одного изображения вообще.
IMG=$(count '<img|background-image|Image src=|\.(webp|jpg|jpeg|png)')
if [ "$IMG" -eq 0 ]; then
  printf '[однообразно] на странице вообще нет изображений\n'
  printf '      → у малого бизнеса фото решают больше вёрстки; взять из выгрузки\n'
fi

echo
if [ "$TIHO" -ge 4 ]; then
  echo "Тихо во всех местах разом — вид не решали, это дефолт генератора."
  echo "Сначала DESIGN.md по references/napravlenie.md, потом пересборка."
  exit 1
fi
if [ "$TIHO" -eq 0 ]; then
  echo "Громкие места на странице есть. Дальше — глазами через playwright:"
  echo "первый экран на десктопе и на телефоне, рядом с референсом."
  exit 0
fi
echo "Тихих мест: $TIHO. Не приговор, но проверь, что громкое место вообще есть —"
echo "оно должно быть ровно одно, а не ноль."
exit 0
