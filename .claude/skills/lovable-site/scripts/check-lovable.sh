#!/bin/bash
# Ищет следы Lovable в собранном прототипе. Пересборка возвращает их обратно,
# поэтому проверка идёт перед каждой выкладкой, а не один раз при заведении
# клиента. Выход 1 — нашлось, выкладывать нельзя.
set -uo pipefail

TARGET="${1:-.}"
[ -e "$TARGET" ] || { echo "нет такого пути: $TARGET" >&2; exit 2; }

FOUND=0
report() {  # report <что нашли> <как чинить> <вывод grep>
  [ -z "$3" ] && return 0
  FOUND=1
  printf '\n[!] %s\n    чинить: %s\n' "$1" "$2"
  printf '%s\n' "$3" | head -5 | sed 's/^/    /'
}

note() {  # то же, но выход не меняет: клиент этого не увидит
  [ -z "$3" ] && return 0
  printf '\n[i] %s\n    %s\n' "$1" "$2"
  printf '%s\n' "$3" | head -3 | sed 's/^/    /'
}

# --include не нужен: в бандле следы попадают и в .js, и в .json карт исходников
INC=(--include='*.html' --include='*.js' --include='*.mjs'
     --include='*.json' --include='*.webmanifest')

# Показываем кусок вокруг совпадения, а не начало строки. Причина: бандл
# минифицирован, вся программа в одной строке на сотню килобайт, и обрезка
# по первым 160 символам печатала случайный код без единого упоминания
# Lovable. Отчёт выглядел ложной тревогой ровно тогда, когда находил
# настоящее — `<title>Lovable App` и `@Lovable` в мета-тегах уехали в бой
# именно потому, что их списали на шум. `-o` с окном в 60 символов по краям
# показывает то самое место.
scan() {
  local pat=".{0,60}($1).{0,60}"
  if [ -d "$TARGET" ]; then (cd "$TARGET" && grep -rnioE "$pat" . "${INC[@]}" 2>/dev/null)
  else grep -nioE "$pat" "$TARGET" 2>/dev/null; fi
}

report "скрипт конструктора" \
       "убрать <script src=\"https://cdn.gpteng.co/gptengineer.js\"> из index.html" \
       "$(scan 'gpteng|gptengineer')"

# Ловим любое упоминание, кроме служебных `__lovable*` ниже: лучше лишний
# раз показать, чем пропустить новый след после очередной пересборки.
report "бейдж или упоминание Lovable" \
       "снять блок «Edit with Lovable» в правом нижнем углу и все упоминания в разметке" \
       "$(scan '(^|[^_])lovable')"

# Крючки для отчёта об ошибках в превью конструктора: вне Lovable этих
# глобальных переменных нет, вызов гасится `?.` и клиент ничего не увидит.
# Раньше они попадали в общую проверку, и та отвечала «выкладывать нельзя»
# на каждой сборке — а проверка, которая всегда красная, перестаёт работать
# вовсе. Убирать их стоит при сдаче сайта, вместе с `lib/lovable-error-reporting`.
note "служебные крючки конструктора в бандле (не видны клиенту)" \
     "выкладке не мешают; вычистить при передаче сайта клиенту" \
     "$(scan '__lovable[a-z]*')"

report "заголовок по умолчанию" \
       "поставить <title> с названием компании клиента" \
       "$(scan '<title>[^<]*(generated project|vite \+ react|lovable)')"

report "generator в мета-тегах" \
       "удалить <meta name=\"generator\">" \
       "$(scan '<meta[^>]+name=.generator')"

# og:image и twitter:image на чужом домене — картинка превью в мессенджерах
report "og:image или twitter:image ведёт не на сайт клиента" \
       "заменить на скриншот самого сайта, положенный рядом" \
       "$(scan '(og:image|twitter:image)[^>]*(lovable|gpteng|placehold)')"


# Иконка вкладки. Раньше здесь было написано «смотреть глазами», и ровно так
# дефолтная иконка Lovable доехала до боевого прототипа kondi-review: в
# закладках у владельца висел розовый значок конструктора, а все текстовые
# проверки были чистые. Глазами её не смотрят — сравниваем по хешу.
FAVICON_LOVABLE="9f504444f85a5af2eef9264b02ae40be"
for f in "$TARGET/favicon.ico" "$TARGET/public/favicon.ico"; do
  [ -f "$f" ] || continue
  h=$(md5sum "$f" | cut -d' ' -f1)
  if [ "$h" = "$FAVICON_LOVABLE" ]; then
    report "иконка вкладки — дефолтная из шаблона конструктора" \
           "нарисовать свою: $f" \
           "$f:1:favicon.ico совпадает с шаблонной по хешу ($h)"
  fi
done

if [ "$FOUND" -eq 0 ]; then
  echo "чисто: следов Lovable в $TARGET не нашлось"
  echo "остаётся глазами: картинка превью og:image — переслать ссылку себе в мессенджер"
  exit 0
fi

printf '\nВыкладывать нельзя. Клиент смотрит на сайт своей компании, а по бейджу\n'
printf 'за минуту выясняет, что сайт собран мышкой, — разговор о цене после\n'
printf 'этого другой.\n'
exit 1
