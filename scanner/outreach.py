"""Генерация холодного письма-предложения под конкретный лид.

Принципы: коротко, одна понятная проблема (не список терминов), язык
выгоды, мягкий CTA, ценность вперёд (бесплатный набросок), строчка-отписка.
"""

from __future__ import annotations

from .models import Lead

# Приоритет «зацепок»: берём ОДНУ самую сильную и понятную владельцу.
# Формулировки — на языке потерянных клиентов, а не технических терминов.
_HOOKS: list[tuple[str, str]] = [
    ("viewport",
     "ваш сайт неудобно открывается с телефона — а сейчас большинство клиентов "
     "ищут именно так, и часть из них просто закрывает страницу"),
    ("битый SSL",
     "у сайта просрочен сертификат безопасности, и браузер встречает посетителей "
     "красным предупреждением — многих это отпугивает ещё до входа"),
    ("нет HTTPS",
     "сайт открывается без защищённого соединения — браузеры помечают его "
     "небезопасным, и это подрывает доверие клиентов"),
    ("Flash",
     "на сайте используется Flash, который уже не работает в современных браузерах "
     "— часть контента посетители просто не видят"),
    ("копирайт устарел",
     "сайт выглядит заброшенным — в подвале ещё старый год, и клиенты нередко "
     "думают, что вы уже не работаете"),
    ("вёрстка на таблицах",
     "сайт заметно устарел внешне — на фоне конкурентов с современными сайтами "
     "это бьёт по доверию"),
    ("устаревшие теги",
     "сайт заметно устарел внешне — на фоне конкурентов с современными сайтами "
     "это бьёт по доверию"),
    ("устаревшая CMS",
     "сайт собран на устаревшей платформе — его тяжело обновлять, и он медленно "
     "грузится, из-за чего часть посетителей уходит"),
]

_FALLBACK_HOOK = ("он выглядит заметно устаревшим — на фоне конкурентов "
                  "с современными сайтами это сразу бросается в глаза")

SIGNATURE = "[Ваше имя]\n[телефон / телеграм]"


def _pick_hook(signals: list[str]) -> str:
    for needle, phrase in _HOOKS:
        if any(needle.lower() in s.lower() for s in signals):
            return phrase
    return _FALLBACK_HOOK


def _name_patronymic(full: str | None) -> str:
    """«Фамилия Имя Отчество» → «Имя Отчество» (обращение по имени-отчеству)."""
    if not full:
        return ""
    parts = full.strip().split()
    if len(parts) >= 3:          # Фамилия Имя Отчество
        return f"{parts[1]} {parts[2]}"
    if len(parts) == 2:          # Имя Отчество (без фамилии)
        return f"{parts[0]} {parts[1]}"
    return parts[0] if parts else ""


def build_call_script(lead: Lead, *, caller_name: str = "") -> str:
    """Короткий скрипт холодного звонка под конкретный лид."""
    company = lead.enrichment.official_name or lead.contacts.company or lead.domain
    who = f"Меня зовут {caller_name}, " if caller_name.strip() else ""
    hook = _pick_hook(lead.signals)

    # ФИО руководителя из ЕГРЮЛ (DaData отдаёт даже на бесплатном тарифе) —
    # проход через секретаря прямо к тому, кто принимает решение.
    boss = _name_patronymic(lead.enrichment.management)
    gate = (
        f"Проход через секретаря (если возьмут не сразу):\n"
        f"«Соедините, пожалуйста, с {boss} — по вопросу сайта компании.»\n\n"
        if boss else ""
    )
    hello = (f"«Здравствуйте, {boss}! " if boss
             else "«Здравствуйте! ")

    return (
        f"{gate}"
        f"Приветствие:\n"
        f"{hello}{who}я занимаюсь сайтами. Звоню по вашему сайту "
        f"{lead.domain} — пара минут найдётся?»\n\n"
        f"Зацепка (проблема):\n"
        f"«Посмотрел ваш сайт и заметил: {hook}. Из-за этого часть клиентов, "
        f"которые вас находят, уходит к конкурентам.»\n\n"
        f"Оффер (сильнее всего — когда прототип уже готов):\n"
        f"«Я уже набросал, как мог бы выглядеть ваш новый сайт — скину прямо сейчас, "
        f"посмотрите. Ни к чему не обязывает.»\n\n"
        f"Выход на решение:\n"
        f"«Подскажите, с кем лучше обсудить обновление сайта? Удобнее скинуть пример "
        f"на почту или в мессенджер?»\n\n"
        f"Ответы на частые возражения:\n"
        f"— «Нет времени» → «Понимаю, не задержу. Скину пример на почту, глянете, "
        f"когда будет удобно — на какой адрес?»\n"
        f"— «У нас уже есть сайт» → «Да, я его и смотрел — как раз про обновление. "
        f"Сейчас он теряет клиентов, особенно с телефонов.»\n"
        f"— «Сколько стоит?» → «Зависит от объёма. Сначала бесплатно покажу концепт, "
        f"потом уже решите, надо ли.»\n"
        f"— «Пришлите на почту» → «Конечно, записываю адрес. Наберу через пару дней "
        f"узнать впечатление, хорошо?»"
    )


def build_message(lead: Lead, *, signature: str = SIGNATURE) -> dict[str, str]:
    """Возвращает {'pitch_subject', 'pitch_body'} — короткое холодное письмо."""
    company = lead.enrichment.official_name or lead.contacts.company or lead.domain
    name = (company or lead.domain).strip()
    hook = _pick_hook(lead.signals)

    subject = f"По сайту {name}"

    body = (
        f"Здравствуйте!\n\n"
        f"Зашёл на {lead.domain} и обратил внимание: {hook}.\n\n"
        f"Мы делаем современные сайты под ключ — адаптивные под телефон, быстрые, "
        f"с удобной формой заявки. Готов бесплатно набросать, как мог бы выглядеть "
        f"ваш новый сайт, без каких-либо обязательств.\n\n"
        f"Прислать пример? Или подскажите, с кем удобнее это обсудить.\n\n"
        f"С уважением,\n{signature}\n\n"
        f"P.S. Если тема неактуальна — просто ответьте, и я больше не побеспокою."
    )
    return {"pitch_subject": subject, "pitch_body": body}
