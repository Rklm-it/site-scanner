"""Отсев агрегаторов/каталогов: это не потенциальные клиенты, а сами справочники.

Держать список всех доменов-агрегаторов вручную бесполезно — их тысячи. Вместо
этого узнаём агрегатор по его же заголовку/описанию: «доска объявлений», «все
банки», «каталог организаций», «справочник», «рейтинг» и т.п. Такие сайты
никому не продашь — они сами и есть каталог, поэтому выкидываем их из выдачи.
"""

from __future__ import annotations

import re

# Фразы-маркеры каталога/агрегатора (подстрока, регистронезависимо).
# Подобраны так, чтобы не задевать обычный бизнес («каталог товаров» у магазина
# сознательно НЕ берём — это нормальный интернет-магазин, живой клиент).
_PHRASES = (
    "доска объявлений", "бесплатных объявлений", "подать объявление",
    "все банки", "все компании", "все организации", "все фирмы", "все предприятия",
    "все салоны", "все магазины города", "все кафе", "все рестораны города",
    "каталог организаций", "каталог компаний", "каталог фирм", "каталог предприятий",
    "каталог сайтов", "каталог организаций и предприятий",
    "справочник организаций", "справочник предприятий", "справочник компаний",
    "справочник телефонов", "телефонный справочник",
    "городской портал", "городской справочник", "бизнес-справочник",
    "агрегатор", "маркетплейс", "прайс-агрегатор",
    "рейтинг банков", "рейтинг компаний", "рейтинг организаций", "рейтинг лучших",
    "сравнить цены", "сравнение цен", "отзывы и цены", "цены и отзывы",
    "объявления о продаже", "частные объявления",
)

_DESC_RE = re.compile(
    r'<meta[^>]+name=["\']description["\'][^>]+content=["\']([^"\']*)["\']', re.I)


def _meta_description(html: str) -> str:
    m = _DESC_RE.search(html or "")
    return m.group(1) if m else ""


def aggregator_reason(*, title: str | None = None, company: str | None = None,
                      html: str | None = None) -> str | None:
    """Возвращает причину («агрегатор: <фраза>»), если сайт — каталог; иначе None."""
    haystack = " ".join(filter(None, [title or "", company or "",
                                       _meta_description(html or "")])).lower()
    for phrase in _PHRASES:
        if phrase in haystack:
            return f"агрегатор/каталог ({phrase})"
    return None
